import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {codeWindowContext,projectContextRegion,contextBoundaryRelation,detectCodeWindowContext} from './code-window-context.mjs';
import {decodeOcrSource} from '../../src/ocr-image.mjs';
const sharp=createRequire(import.meta.url)('sharp');
const image={width:1000,height:500},window={left:400,top:200,width:100,height:20};
assert.deepEqual(codeWindowContext(image,window),{left:350,top:170,width:200,height:80});
assert.deepEqual(codeWindowContext(image,{left:0,top:0,width:10,height:10}),{left:0,top:0,width:15,height:25});
for(const bad of [{...window,left:-1},{...window,width:1001},{...window,top:NaN}])assert.throws(()=>codeWindowContext(image,bad));
assert.throws(()=>codeWindowContext(image,window,{verticalScale:9}));
const projected=projectContextRegion({left:.25,top:.25,width:.5,height:.5,score:.9},{left:100,top:50,width:200,height:100},image);
assert.deepEqual(projected,{left:150,top:75,width:100,height:50,score:.9});
assert.throws(()=>projectContextRegion({left:.9,top:0,width:.2,height:.5},window,image));
const inside=contextBoundaryRelation(window,{left:420,top:204,width:60,height:10});
assert.equal(inside.regionFractionInside,1);assert.equal(inside.physicalCodeExtentVerified,false);
const clipped=contextBoundaryRelation(window,{left:450,top:204,width:100,height:10});
assert.equal(clipped.extendsRight,true);assert.equal(clipped.regionFractionInside,.5);assert.equal(clipped.mayClearCodeConflict,false);
assert.equal(contextBoundaryRelation(window,{left:600,top:100,width:20,height:10}).overlaps,false);
const decoded=await decodeOcrSource(await sharp({create:{width:1000,height:500,channels:3,background:'red'}}).png().toBuffer());
let calls=0;
const result=await detectCodeWindowContext({async detect(bytes){calls++;assert.equal((await sharp(bytes).metadata()).width,600);
  return {regions:[{left:.5,top:.5,width:.4,height:.1,score:.9}]};}},decoded,window);
assert.equal(calls,1);assert.equal(result.regions.length,1);assert.equal(result.regions[0].relation.extendsRight,true);
assert.equal(result.status,'diagnostic-only-not-binding');
await assert.rejects(detectCodeWindowContext({async detect(){throw Error('detector failed');}},decoded,window),/detector failed/);
await assert.rejects(detectCodeWindowContext({async detect(){return {regions:Array(2).fill({})};}},decoded,window,{maxRegions:1}),/Incomplete/);
console.log('Code window context geometry and non-binding safeguards PASS');
